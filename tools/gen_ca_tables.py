import math
BR=44100/32
def arr(name,typ,vals,per=16):
    s=f"static const {typ} {name}[{len(vals)}] = {{\n"
    for i in range(0,len(vals),per): s+="    "+", ".join(str(v) for v in vals[i:i+per])+",\n"
    return s+"};\n"
out="/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/gen_ca_tables.py: do not edit by hand. */\n"
out+="/* log2(h) in Q12, h = 1..64 (index h - 1) */\n"+arr("CA_L2",'uint32_t',[round(4096*math.log2(h)) for h in range(1,65)])
T=[0.06*(8/0.06)**(i/63) for i in range(64)]
out+="/* harmonic slew: the time (ms) shown, and the one-pole step per 32 frames, Q16 (tau = time / 3) */\n"
out+=arr("CA_SLEW_MS",'uint16_t',[round(t*1000) for t in T])
out+=arr("CA_SLEW_K",'uint32_t',[max(1,round(65536*(1-math.exp(-1/((t/3)*BR))))) for t in T])
R=[0.1*(8/0.1)**(i/63) for i in range(64)]
out+="/* automaton clock: the period in ms, 0.1 .. 8 steps a second */\n"+arr("CA_RATE_MS",'uint16_t',[round(1000/r) for r in R])
KF=[]
for s in range(132):
    f=440*2**((s-69)/12); tau=max(0.02,3/f); KF.append(max(1,round(65536*(1-math.exp(-1/(tau*BR))))))
out+="/* the fastest a partial may move, by its MIDI note: at least ~3 of its own cycles (tau), and 20 ms */\n"+arr("CA_KF",'uint32_t',KF)
open('firmware/src/ca_tables.h','w').write(out)

