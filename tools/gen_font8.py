#!/usr/bin/env python3
"""The chunky screen font: font8x8_basic (Daniel Hepper, public domain, after the IBM VGA fonts), each 8 x 8 glyph
drawn double height -> 8 x 16, in the firmware's font format (4-bit glyphs, see gfx.c), as FONT_C; and the 8 x 8
bitmaps as they are (FONT8_RAW), for the boot screen's big letters.

Usage: python3 tools/gen_font8.py path/to/font8x8_basic.h   -> firmware/src/font_chunky.h
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()
body = src.split("{", 1)[1]
rows = re.findall(r"\{([^}]*)\}", body)
glyphs = [[int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", r)] for r in rows][:128]
assert len(glyphs) == 128 and all(len(g) == 8 for g in glyphs)

FIRST, LAST = 32, 126
data, off = [], []
for ch in range(FIRST, LAST + 1):
    off.append(len(data))
    for y in range(16):                         # each row twice
        bits = glyphs[ch][y // 2]
        for x in range(0, 8, 2):                # two 4-bit pixels a byte, the left one high (bit 0 = left)
            a = 15 if bits >> x & 1 else 0
            b = 15 if bits >> (x + 1) & 1 else 0
            data.append(a << 4 | b)
n = LAST - FIRST + 1
raw = [b for ch in range(FIRST, LAST + 1) for b in glyphs[ch]]
arr = lambda name, typ, v: f"static const {typ} {name}[{len(v)}] = {{" + ",".join(map(str, v)) + "};"
out = [
    "/* SPDX-License-Identifier: GPL-3.0-only */",
    "/* Generated by tools/gen_font8.py from font8x8_basic.h (Daniel Hepper, public domain): do not edit by hand. */",
    arr("FONT_C_DATA", "uint8_t", data),
    arr("FONT_C_OFF", "uint16_t", off),
    arr("FONT_C_ADV", "uint8_t", [8] * n),
    arr("FONT_C_BW", "uint8_t", [8] * n),
    "static const felucca_font_t FONT_C = { 16, 0, 32, 126, FONT_C_ADV, FONT_C_BW, FONT_C_OFF, FONT_C_DATA };",
    "/* the 8 x 8 bitmaps, ASCII 32..126: row by row, bit 0 = the left pixel */",
    arr("FONT8_RAW", "uint8_t", raw),
]
dst = Path(__file__).resolve().parent.parent / "firmware" / "src" / "font_chunky.h"
dst.write_text("\n".join(out) + "\n")
print(dst, n, "glyphs")
